using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;

namespace Fdw.WebMcp.Hosting;

/// <summary>
/// Generates the <c>webmcp.js</c> IIFE that registers AI-agent tools via
/// <c>document.modelContext.registerTool()</c> (WebMCP W3C standard).
/// </summary>
public sealed class WebMcpJsGenerator
{
    private readonly IWebMcpToolRegistry _registry;
    private readonly ILogger<WebMcpJsGenerator> _logger;

    /// <summary>
    /// Initializes a new instance of <see cref="WebMcpJsGenerator"/>.
    /// </summary>
    public WebMcpJsGenerator(
        IWebMcpToolRegistry registry,
        ILogger<WebMcpJsGenerator>? logger = null)
    {
        _registry = registry;
        _logger = logger ?? NullLogger<WebMcpJsGenerator>.Instance;
    }

    /// <summary>
    /// Builds and returns the full JavaScript source string.
    /// Returns a no-op script if no tools have been registered.
    /// </summary>
    /// <param name="settings">
    /// The host's WebMCP settings: the header every call carries the client key in, and the key when
    /// the host serves one.
    /// </param>
    public string Generate(WebMcpHostSettings settings)
    {
        ArgumentNullException.ThrowIfNull(settings);
        WebMcpLog.ServingWebMcpJs(_logger, _registry.Tools.Count);
        WebMcpLog.GeneratingScript(_logger, _registry.Tools.Count);

        WebMcpLog.ClientKeyInjection(_logger, settings.ApiKeyHeader, !string.IsNullOrEmpty(settings.ClientApiKey));

        var sb = new StringBuilder();
        sb.AppendLine("// Generated by Fdw WebMCP");
        sb.AppendLine("// Registers AI agent tools via document.modelContext (WebMCP W3C standard).");
        sb.AppendLine("// The spec moved the API from navigator to document because tools belong to a");
        sb.AppendLine("// page, and Chrome 150 deprecated the navigator form while the Chrome 149");
        sb.AppendLine("// origin trial still serves it. Prefer document, accept navigator, so one");
        sb.AppendLine("// generated script works across the Chrome 149-156 trial window.");
        sb.AppendLine("(function() {");
        sb.AppendLine("  var modelContext =");
        sb.AppendLine("    (typeof document !== 'undefined' && document.modelContext) ||");
        sb.AppendLine("    (typeof navigator !== 'undefined' && navigator.modelContext) ||");
        sb.AppendLine("    null;");
        sb.AppendLine("  if (!modelContext) return;");
        sb.AppendLine();
        sb.AppendLine("  // Path parameters travel in the URL, so they are removed from the body a tool sends.");
        sb.AppendLine("  function strip(input, names) {");
        sb.AppendLine("    const out = {};");
        sb.AppendLine("    for (const k of Object.keys(input || {})) if (!names.includes(k)) out[k] = input[k];");
        sb.AppendLine("    return out;");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  // Only values the agent actually supplied are sent: an omitted filter must widen");
        sb.AppendLine("  // the result, not narrow it to the empty string.");
        sb.AppendLine("  function query(input, names) {");
        sb.AppendLine("    const parts = [];");
        sb.AppendLine("    for (const n of names) {");
        sb.AppendLine("      const v = (input || {})[n];");
        sb.AppendLine("      if (v === undefined || v === null || v === \"\") continue;");
        sb.AppendLine("      parts.push(encodeURIComponent(n) + \"=\" + encodeURIComponent(v));");
        sb.AppendLine("    }");
        sb.AppendLine("    return parts.join(\"&\");");
        sb.AppendLine("  }");
        sb.AppendLine();

        foreach (var tool in _registry.Tools)
        {
            AppendTool(sb, tool, settings);
        }

        sb.AppendLine("})();");

        return sb.ToString();
    }

    // ── Per-tool JavaScript block ────────────────────────────────────────────

    private void AppendTool(StringBuilder sb, WebMcpToolDescriptor tool, WebMcpHostSettings settings)
    {
        sb.AppendLine("  modelContext.registerTool({");
        sb.AppendLine(CultureInfo.InvariantCulture, $"    name: {JsonString(tool.Name)},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"    description: {JsonString(tool.Description)},");

        if (tool.ReadOnly)
        {
            sb.AppendLine("    annotations: { readOnlyHint: true },");
        }

        // One plan per tool, shared with the MCP transport. The script renders it; it decides nothing.
        var plan = WebMcpToolPlan.Create(tool, _logger);
        var propertyCount = AppendInputSchema(sb, plan);
        AppendExecute(sb, plan, settings);

        sb.AppendLine("  });");
        sb.AppendLine();

        WebMcpLog.ToolScriptEmitted(_logger, tool.Name, tool.HttpMethod, tool.Route, propertyCount);
    }

    private static int AppendInputSchema(StringBuilder sb, WebMcpToolPlan plan)
    {
        // Gated on the request type alone. Gating on the verb, as this once did, gave every GET and
        // DELETE an empty schema even when the endpoint declared a request DTO -- so a path parameter
        // had no field to arrive through and a list tool could not be filtered. "Has a body" and "has
        // inputs" are different questions.
        if (plan.Tool.RequestType is null)
        {
            sb.AppendLine("    inputSchema: {");
            sb.AppendLine("      type: \"object\",");
            sb.AppendLine("      properties: {},");
            sb.AppendLine("      required: []");
            sb.AppendLine("    },");
            return 0;
        }

        sb.AppendLine("    inputSchema: {");
        sb.AppendLine("      type: \"object\",");
        sb.AppendLine("      properties: {");

        for (var i = 0; i < plan.Inputs.Count; i++)
        {
            var input = plan.Inputs[i];
            var comma = i < plan.Inputs.Count - 1 ? "," : string.Empty;

            if (string.IsNullOrEmpty(input.Format))
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"        {JsonKey(input.Name)}: {{ \"type\": {JsonString(input.JsonType)} }}{comma}");
            }
            else
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"        {JsonKey(input.Name)}: {{ \"type\": {JsonString(input.JsonType)}, \"format\": {JsonString(input.Format)} }}{comma}");
            }
        }

        sb.AppendLine("      },");

        // Path parameters are the one set whose requiredness is structural rather than a matter of
        // validation policy: the URL cannot be built without them. Everything else stays optional and
        // is the endpoint's own validation to enforce.
        sb.AppendLine(
            CultureInfo.InvariantCulture,
            $"      required: [{string.Join(", ", plan.PathProperties.Select(JsonString))}]");

        sb.AppendLine("    },");

        return plan.Inputs.Count;
    }

    private static void AppendExecute(StringBuilder sb, WebMcpToolPlan plan, WebMcpHostSettings settings)
    {
        var tool = plan.Tool;
        var headers = HeaderLiteral(plan.HasBody, settings);
        var recoveryHeaders = HeaderLiteral(withBody: false, settings);

        sb.AppendLine("    execute: async function(input) {");
        sb.AppendLine(CultureInfo.InvariantCulture, $"      let url = {UrlExpression(plan)};");

        if (plan.QueryProperties.Count > 0)
        {
            // Without this a GET tool could be called but never narrowed -- every list tool would
            // return the unfiltered collection whatever the agent asked for.
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"      const q = query(input, [{string.Join(", ", plan.QueryProperties.Select(JsonString))}]);");
            sb.AppendLine("      if (q) url += \"?\" + q;");
        }

        sb.AppendLine("      const init = {");
        sb.AppendLine(CultureInfo.InvariantCulture, $"        method: {JsonString(tool.HttpMethod)},");
        if (plan.HasBody)
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"        headers: {headers},");

            // Path parameters are stripped from the body: they are already in the URL, and an endpoint
            // that receives the same value twice can disagree with itself about which one binds.
            // The preset field, when declared, is merged in AFTER stripping so it wins even if the
            // agent's input happened to carry the same key -- the tool's own identity decides this
            // value, not whatever the agent sent.
            var strippedBody = $"strip(input, [{string.Join(", ", plan.PathProperties.Select(JsonString))}])";
            var bodyExpression = tool is { PresetFieldName: { } field, PresetValue: { } value }
                ? $"Object.assign({strippedBody}, {{ {JsonKey(field)}: {JsonString(value)} }})"
                : strippedBody;

            sb.AppendLine(CultureInfo.InvariantCulture,
                $"        body: JSON.stringify({bodyExpression})");
        }
        else
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"        headers: {headers}");
        }

        sb.AppendLine("      };");
        sb.AppendLine("      const r = await fetch(url, init);");
        AppendFailureHandling(sb, plan, recoveryHeaders);
        sb.AppendLine("      return await r.json();");
        sb.AppendLine("    }");
    }

    /// <summary>Emits the JS expression that builds the request URL.</summary>
    /// <remarks>
    /// Concatenated rather than string-replaced so each value is encoded on the way in. A value
    /// carrying '/' or '?' would otherwise reshape the path it was substituted into.
    /// </remarks>
    private static string UrlExpression(WebMcpToolPlan plan)
        => string.Join(" + ", plan.RouteParts.Select(part => part.IsParameter
            ? $"encodeURIComponent(input[{JsonString(part.Text)}])"
            : JsonString(part.Text)));

    /// <summary>Emits the non-OK branch, including the valid-values recovery when one is available.</summary>
    private static void AppendFailureHandling(StringBuilder sb, WebMcpToolPlan plan, string recoveryHeaders)
    {
        if (plan.RecoveryProperty is null)
        {
            sb.AppendLine("      if (!r.ok) return { error: r.status + \" \" + r.statusText };");
            return;
        }

        // A bare 404 is a dead end for an agent: it cannot tell a wrong identifier from an empty
        // result, and nothing in the response says what a right one would look like. Answering with
        // the collection the parameter selects from turns that into one more round trip.
        //
        // The recovery call reuses these headers, so it runs as the same principal -- an agent can
        // never be handed values it could not have listed itself.
        sb.AppendLine("      if (!r.ok) {");
        sb.AppendLine("        const failure = { error: r.status + \" \" + r.statusText };");
        sb.AppendLine("        try {");
        sb.AppendLine(CultureInfo.InvariantCulture,
            $"          const alt = await fetch({JsonString(plan.Tool.ParentListRoute!)}, {{ method: \"GET\", headers: {recoveryHeaders} }});");
        sb.AppendLine("          if (alt.ok) {");
        sb.AppendLine("            failure.validValues = await alt.json();");
        sb.AppendLine(CultureInfo.InvariantCulture,
            $"            failure.hint = {JsonString($"'{plan.RecoveryProperty}' did not match. failure.validValues lists what is available; '{plan.Tool.ParentListToolName}' returns the same set.")};");
        sb.AppendLine("          }");
        sb.AppendLine("        } catch (e) { /* recovery is best-effort; the original failure still returns */ }");
        sb.AppendLine("        return failure;");
        sb.AppendLine("      }");
    }

    /// <summary>Builds the header literal for a request.</summary>
    /// <param name="withBody">Whether the request carries a JSON body.</param>
    /// <param name="settings">The header and client key the host's settings give.</param>
    private static string HeaderLiteral(bool withBody, WebMcpHostSettings settings)
        => "{ " + string.Join(", ", WebMcpRequestHeaders
                .For(withBody, settings.ApiKeyHeader, settings.ClientApiKey)
                .Select(header => $"{JsonString(header.Key)}: {JsonString(header.Value)}")) + " }";

    // ── Helpers ──────────────────────────────────────────────────────────────

    private static string JsonString(string value)
    {
        // Minimal JSON string escaping for JS output
        return "\"" + value
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            + "\"";
    }

    private static string JsonKey(string name)
        => JsonString(name);
}
