/// <summary>
/// Collection of ETL pipeline service types.
/// Generated by ServiceTypeCollectionGenerator with high-performance lookups.
/// </summary>
/// <remarks>
/// This ServiceTypeCollection manages ETL pipeline ENGINE types (today only Graph).
/// An engine type is a service with behavior: it registers its factory and the provider for its own
/// implementation row (GraphPipelineConfiguration over pipe.GraphPipelineConfiguration), then registers that
/// provider into the EtlPipeline domain under its own name.
/// </remarks>
[ExcludeFromCodeCoverage]
[ServiceTypeCollection(
    typeof(EtlPipelineTypeBase<IEtlPipeline, IEtlPipelineFactory<IEtlPipeline, IEtlPipelineImplementationConfiguration>, IEtlPipelineImplementationConfiguration>),
    typeof(IEtlPipelineType),
    typeof(EtlPipelineTypes),
    ServiceInterface = typeof(IEtlPipeline),
    ProviderType = typeof(EtlPipelineProvider),
    ProviderInterface = typeof(IEtlPipelineProvider),
    ServiceCategory = "Pipeline")]
public partial class EtlPipelineTypes : ServiceTypeCollectionBase<
    EtlPipelineTypeBase<IEtlPipeline, IEtlPipelineFactory<IEtlPipeline, IEtlPipelineImplementationConfiguration>, IEtlPipelineImplementationConfiguration>,
    IEtlPipelineType<IEtlPipeline, IEtlPipelineImplementationConfiguration, IEtlPipelineFactory<IEtlPipeline, IEtlPipelineImplementationConfiguration>>>
{
    /// <summary>
    /// The connection this domain's configuration rows are read from and written to.
    /// </summary>
    public static string ConfigurationConnection => PlatformConnection.Name;

    /// <summary>
    /// The connection this domain's operational rows live in. The host must set it; there is no default.
    /// </summary>
    /// <remarks>
    /// Deliberately without an initializer, unlike <see cref="ConfigurationConnection"/>. That one may
    /// default because <c>PlatformConfiguration</c> is declared in <c>configurationSchema.json</c> and
    /// is therefore known before any row is read. An operational store is a row INSIDE that store, so a
    /// default here would name a store the application merely hopes exists — the absence the
    /// no-fallbacks rule exists to catch, rather than the ConfigurationConnection case it resembles.
    /// Not proven at registration: every host registers this domain as part of the platform bootstrap,
    /// including hosts that never touch its operational store, so refusing to start them would demand
    /// a value a correct host cannot supply. The sites that read it report it instead.
    /// </remarks>
    public static string? OperationalConnection { get; set; }

    // Configure(), Register() and Initialize() are source-generated.
    // Each pipeline type registers its own configuration via its Implementation.

    /// <summary>
    /// Registers execution-inspection singletons consumed by test-mode endpoints.
    /// Call this BEFORE any endpoint-activation path that injects these interfaces.
    /// </summary>
    /// <remarks>
    /// Why: IPipelineExecutionInspector / IPipelineTestController are consumed by
    /// InspectEdgeEndpoint, StepExecutionEndpoint, and ResumeTestExecutionEndpoint at
    /// FastEndpoints activation time. They have no Implementation of their own — they
    /// are cross-cutting singletons that belong to the ETL execution subsystem, not to a
    /// pipeline type variant. RegisterAdditionalServices is the canonical home for
    /// non-variant singletons inside a ServiceTypeCollection.
    /// </remarks>
    public static void RegisterAdditionalServices(IServiceCollection services)
    {
        services.TryAddSingleton<IPipelineExecutionInspector, PipelineExecutionInspector>();
        services.TryAddSingleton<IPipelineTestController, PipelineTestController>();

        // The calculations a query filter names for its values (FDW-2333). The data query endpoints take it by interface; a host
        // that registers the pipeline types has the Transformation provider and the settings it reads.
        services.TryAddSingleton(TimeProvider.System);
        services.TryAddSingleton<IFilterCalculations, BuiltFilterCalculations>();
    }

    /// <summary>
    /// Registers the pipeline execution queue (<see cref="IPipelineExecutionQueue"/>) and its
    /// background consumer (<see cref="PipelineExecutionBackgroundService"/>).
    /// </summary>
    /// <remarks>
    /// Why a shared helper: OrchestrationNodeOrchestrator (Fdw.Services.Etl.Projects) takes
    /// IPipelineExecutionQueue as a hard (non-nullable) constructor dependency to dispatch
    /// leaf-node pipeline runs. Every host that registers OrchestrationTypes must get a working
    /// queue, not just hosts that separately opt into the background executor — this is the
    /// canonical, option-owned home for that registration (same domain as PipelineExecutionQueue
    /// itself), mirroring RegisterAdditionalServices above.
    /// <para>
    /// Idempotent by design: safe to call from multiple registration paths (both
    /// the pipeline options and OrchestrationTypes.Register call this) regardless
    /// of call order.
    /// </para>
    /// </remarks>
    /// <param name="services">The service collection.</param>
    public static void RegisterPipelineExecutionQueue(IServiceCollection services)
    {
        // The requests of the runs that wait for approval (FDW-1937), kept beside the queue they would have entered.
        services.TryAddSingleton<IPipelineRunHolds, PipelineRunHolds>();

        if (services.Any(d => d.ServiceType == typeof(IPipelineExecutionQueue)))
            return;

        // Why only a host that names its operational store hosts the services that run pipelines (FDW-3975): the ETL host names the store its runs are kept in. A host that only
        // sends runs to it, the scheduler, has no queue to consume, no stored requests to take up again (a second host taking up the ETL host's runs would run them twice) and
        // no alerts to time, and it cannot read the store it does not name, so these services would only log that.
        var hostsRuns = OperationalConnection is { Length: > 0 };

        // What the host keeps of each run it accepts, so a restart can take the runs that were held or waiting up again (FDW-3216). The queue takes the
        // request of every run it accepts into it.
        services.TryAddSingleton<IPipelineRunRequestStore, PipelineRunRequestStore>();

        // The thresholds on waiting runs (FDW-3161, FDW-3975): one monitor is the observer the scheduler tells, the check a trigger asks before it takes a run (the gate asks
        // the evaluator which HoldNewRuns rules hold), and the loop that has the evaluator judge the thresholds attached to pipelines, schedules and the server.
        services.TryAddSingleton<IWaitThresholdSource, WaitThresholdSource>();
        services.TryAddScoped<IWaitThresholdStore, WaitThresholdStore>();
        services.TryAddScoped<IPipelineFailureConfigurations, PipelineFailureConfigurations>();
        services.TryAddScoped<IPipelineRunHistory, PipelineRunHistory>();
        services.TryAddScoped<IPipelineDisableRecord, PipelineDisableRecord>();
        services.TryAddScoped<IPipelineDisabler, PipelineDisabler>();
        services.TryAddScoped<PipelineFailureReporter>();
        services.TryAddSingleton<WaitHoldGate>();
        services.TryAddSingleton<WaitThresholdReporter>();
        services.TryAddSingleton<WaitThresholdMonitor>();
        services.TryAddSingleton<IPipelineWaitObserver>(provider => provider.GetRequiredService<WaitThresholdMonitor>());
        services.TryAddSingleton<IPipelineRunStopCheck>(provider => provider.GetRequiredService<WaitThresholdMonitor>());
        if (hostsRuns)
        {
            services.AddHostedService(provider => provider.GetRequiredService<WaitThresholdMonitor>());
        }

        // The number of triggers the queue holds is a setting (FDW-3155), read when the host first needs the queue.
        services.AddSingleton(PipelineExecutionQueue.Create);
        services.TryAddSingleton<PipelineRunScheduler>();

        // What the live view reads: the components of the runs in flight (FDW-3382).
        services.TryAddSingleton<RunningFlows>();

        // What the host holds of each run it has queued, so cancelling, pausing and resuming an execution reaches the run (FDW-2950).
        services.TryAddSingleton<PipelineRunControl>();
        services.TryAddSingleton<Fdw.Operations.Abstractions.Execution.IExecutionRunControl>(
            provider => provider.GetRequiredService<PipelineRunControl>());

        // How the StopRun escalation of a threshold stops a run this host holds (FDW-3865).
        services.TryAddSingleton<Fdw.Operations.Abstractions.Thresholds.IRunStopper>(
            provider => new ThresholdRunStopper(provider.GetRequiredService<PipelineRunControl>()));
        services.AddSingleton<IPipelineExecutionQueue>(provider => provider.GetRequiredService<PipelineExecutionQueue>());

        // How long a stopping host lets the runs in flight finish is a setting (FDW-3786), read when the host first needs it; the host's shutdown timeout
        // follows it, since the default of the generic host (30 seconds) would end the host before the runs have had their time.
        services.AddSingleton(PipelineStopGrace.Create);
        services.AddOptions<Microsoft.Extensions.Hosting.HostOptions>()
            .Configure<PipelineStopGrace>((options, grace) => options.ShutdownTimeout = grace.ShutdownTimeout);
        if (hostsRuns)
        {
            services.AddHostedService<PipelineExecutionBackgroundService>();
            services.AddHostedService<PipelineComponentsPublisher>();
        }

        // The timer that sends the levels of open escalation alerts as they fall due (FDW-3863). Only the host that runs pipelines runs it: the alerts are opened by thresholds
        // judged there, and a host that serves requests only has no use for a timer.
        services.TryAddSingleton(TimeProvider.System);
        if (hostsRuns)
        {
            services.AddHostedService<Fdw.Operations.Escalation.EscalationBackgroundService>();
        }

        // Scoped: it takes the execution tracker and the data gateways, which are per scope. A pipeline that starts another and
        // an orchestration node that dispatches its members both start runs through it (FDW-1381).
        services.TryAddScoped<IPipelineRunStarter, PipelineRunStarter>();

        // The row-flow engine (FDW-1386). It holds no per-run state, so one executor serves every run.
        services.TryAddSingleton<Fdw.Services.Etl.Abstractions.Flow.IFlowExecutor, Fdw.Services.Etl.Flow.FlowExecutor>();
    }

    /// <summary>
    /// Sets this collection's Register body: the option collect, then this domain's provider.
    /// </summary>
    /// <remarks>
    /// The provider is one registration for the whole collection and this declaration already names it,
    /// so the body that registers it is written here beside the declaration. Setting it as the phase's
    /// body is what makes it replaceable: an application calling <c>Registration(...)</c> replaces the
    /// collect and this registration together, which is the correct semantic for a host taking over phase 2.
    /// </remarks>
    static EtlPipelineTypes()
    {
        var providerService = typeof(IEtlPipelineProvider).ToString();

        Registration((builder, loggerFactory) =>
        {
            var log = loggerFactory?.CreateLogger<EtlPipelineTypes>() ?? NullLogger<EtlPipelineTypes>.Instance;

            // The domain's own base registration goes FIRST -- each option decorates this
            // registration (wraps its factory) from its own Register() call below, so it has to
            // already exist in builder.Services by the time that runs.
            builder.Services.AddScoped<IEtlPipelineProvider>(sp =>
            {
                var provider = new EtlPipelineProvider(
                    sp.GetService<ILoggerFactory>()?.CreateLogger<EtlPipelineProvider>()
                    ?? NullLogger<EtlPipelineProvider>.Instance);

                var stLogger = sp.GetService<ILoggerFactory>()?.CreateLogger<EtlPipelineTypes>()
                    ?? NullLogger<EtlPipelineTypes>.Instance;
                ServiceTypeLog.DomainProviderConstructing(stLogger, nameof(EtlPipelineTypes), provider.GetType().Name);
                try
                {
                    if (sp.GetService<IPipelineConfigurationProvider>() is { } cfgProvider)
                    {
                        var domainResult = provider.Register(cfgProvider);
                        if (domainResult.IsSuccess)
                            ServiceTypeLog.DomainConfigurationSourceAttached(stLogger, nameof(EtlPipelineTypes), provider.GetType().Name, cfgProvider.GetType().Name);
                        else
                            ServiceTypeLog.DomainConfigurationSourceRejected(stLogger, nameof(EtlPipelineTypes), provider.GetType().Name, cfgProvider.GetType().Name, domainResult.CurrentMessage);
                    }
                    else
                    {
                        ServiceTypeLog.DomainHasNoConfigurationSource(
                            stLogger,
                            nameof(EtlPipelineTypes),
                            provider.GetType().Name,
                            typeof(IImplementationConfigurationProvider<IPipelineImplementationConfiguration>).ToString());
                    }
                }
                catch (Exception ex)
                {
                    ServiceTypeLog.FactoryRegistrationException(stLogger, ex, nameof(EtlPipelineTypes));
                    throw;
                }

                return provider;
            });

            foreach (var option in Options)
            {
                var optionRegistered = option.Register(builder, loggerFactory);
                if (optionRegistered.IsFailure)
                    return optionRegistered;
            }

            var declaredOptions = Options;
            var optionNames = string.Join(", ", declaredOptions.Select(option => option.Name));

            ServiceTypeLog.DomainOptionsCollected(log, nameof(EtlPipelineTypes), declaredOptions.Length, optionNames);
            ServiceTypeLog.DomainProviderDeclared(log, nameof(EtlPipelineTypes), providerService);

            if (declaredOptions.Length == 0)
                ServiceTypeLog.DomainRegisteredWithNoOptions(log, nameof(EtlPipelineTypes), providerService);
            else
                ServiceTypeLog.DomainRegistered(log, nameof(EtlPipelineTypes), declaredOptions.Length, optionNames, providerService);

            return GenericResult<IHostApplicationBuilder>.Success(builder);
        });
    }
}
