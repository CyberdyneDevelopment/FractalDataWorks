using System.Diagnostics.CodeAnalysis;
using Fdw.Collections.Attributes;
using Fdw.Results;

namespace Fdw.Data.Abstractions.Results;

/// <summary>
/// A value is not a value of the data type it was to be converted to.
/// </summary>
/// <remarks>
/// 21003 sits in the validation band (category 2) beside this collection's other specific refusals (21000 to 21002), and
/// names the meaning the catalog calls InvalidInput: the value is the caller's input, so the answer is a 400 naming the
/// type, never a 500. It is not 20001, which InvalidCanonicalLocationFormat already holds in this collection: two options
/// sharing an id make the generated ById throw on first use (the same collision FDW-955 moved DataClassificationUnknown
/// off). The message does not carry the value; the caller names the field or parameter it came from.
/// </remarks>
[TypeOption(typeof(DataStoresResultCodes), "DataValueNotConvertible", RestrictToCurrentCompilation = true)]
[ExcludeFromCodeCoverage]
public sealed class DataValueNotConvertibleCode : DataStoresResultCodeBase
{
    /// <summary>Initializes a new instance of the <see cref="DataValueNotConvertibleCode"/> class.</summary>
    public DataValueNotConvertibleCode()
        : base(21003, "DataValueNotConvertible", ResultSeverities.ByName("Error"),
            "A {ValueType} value is not a valid {DataType}",
            isRetryable: false)
    {
    }
}
