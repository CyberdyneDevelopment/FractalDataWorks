/// <summary>
/// Collection of connection service types.
/// Generated by ServiceTypeCollectionGenerator with high-performance lookups.
/// </summary>
/// <remarks>
/// <para>
/// This is the <b>reference implementation</b> for ServiceTypeCollections. New collections
/// should follow the same structure: open-generic base class, generic + marker interfaces,
/// and concrete options that resolve type parameters to unique types.
/// </para>
/// <para>
/// Cross-assembly options (e.g., <c>MsSqlConnectionType</c> in
/// <c>ReferenceConnections.MsSql.ServiceType</c>) are registered via a <c>[ModuleInitializer]</c>
/// generated by <c>Fdw.Registration.SourceGenerators</c> in the entry point project.
/// </para>
/// </remarks>
[ExcludeFromCodeCoverage]
[ServiceTypeCollection(
    typeof(ConnectionTypeBase<IGenericConnection, IConnectionFactory<IGenericConnection, IConnectionImplementationConfiguration>, IConnectionImplementationConfiguration>),
    typeof(IConnectionType),
    typeof(ConnectionTypes),
    ServiceInterface = typeof(IGenericConnection),
    ProviderType = typeof(ConnectionProvider),
    ProviderInterface = typeof(IConnectionProvider),
    ServiceCategory = "Connection")]
public partial class ConnectionTypes : ServiceTypeCollectionBase<
    ConnectionTypeBase<IGenericConnection, IConnectionFactory<IGenericConnection, IConnectionImplementationConfiguration>, IConnectionImplementationConfiguration>,
    IConnectionType<IGenericConnection, IConnectionImplementationConfiguration, IConnectionFactory<IGenericConnection, IConnectionImplementationConfiguration>>>
{
    /// <summary>
    /// Sets this collection's Register body: the option collect, then this domain's provider.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The provider is one registration for the whole collection, and this declaration already names it
    /// — so the body that registers it is written here, beside the declaration, rather than emitted
    /// around the phase or folded into a per-option cascade. The phase is handed the builder, which is
    /// all the registration needs.
    /// </para>
    /// <para>
    /// Setting it as the phase's body is what makes it replaceable: an application calling
    /// <c>Registration(...)</c> in its own start-up replaces the collect and this registration together,
    /// which is the correct semantic — a host that supplies its own phase 2 is taking responsibility for
    /// the whole of it, and the phase reports that it is running a custom implementation.
    /// </para>
    /// <para>
    /// Why a static constructor: it runs when the generated <c>[ModuleInitializer]</c> — a member of this
    /// class — is invoked at assembly load, which is before anything can read the collection. Declaring
    /// it also removes <c>beforefieldinit</c>, so initialization is precise rather than merely eventual.
    /// </para>
    /// </remarks>
    /// <summary>
    /// The connection this domain's configuration rows are read from and written to.
    /// </summary>
    /// <remarks>
    /// The host's <c>ConnectionRoles.Platform</c> declaration, so a host points the whole domain at its own
    /// configuration store. Every implementation of a connection lives in the same store as
    /// the connection row that owns it — the foreign key is declared on that row and cannot span
    /// connections — so this one value settles the domain and its implementations together.
    /// </remarks>
    public static string ConfigurationConnection => PlatformConnection.Name;

    static ConnectionTypes()
    {
        var collectOptions = RegisterFunc;

        var providerService = typeof(IConnectionProvider).ToString();

        Registration((builder, loggerFactory) =>
        {
            var log = loggerFactory?.CreateLogger<ConnectionTypes>() ?? NullLogger<ConnectionTypes>.Instance;

            ConnectionProviderLogger.DomainConfigurationRegistering(
                loggerFactory?.CreateLogger<ConnectionConfigurationProvider>()
                ?? NullLogger<ConnectionConfigurationProvider>.Instance,
                nameof(ConnectionConfigurationProvider));

            // The concrete type is registered as well as the interface, and the interface resolves
            // to it, so both are one instance. Endpoints take the concrete provider - 25 of them do
            // - and registering only the interface leaves every one of them unactivatable. That
            // surfaces as FastEndpoints failing at MapFastEndpoints rather than as a missing
            // registration, which points at the endpoint instead of at this line.
            builder.Services.TryAddSingleton<ConnectionConfigurationProvider>(sp =>
                new ConnectionConfigurationProvider(
                    sp.GetService<ILogger<ConnectionConfigurationProvider>>()!,
                    sp.GetRequiredService<IConfigurationGatewayProvider>(), ConnectionTypes.ConfigurationConnection, "conn", "Connection"));

            builder.Services.TryAddSingleton<IConnectionConfigurationProvider>(sp => sp.GetRequiredService<ConnectionConfigurationProvider>());

            // ConnectionGrant (FDW-1581): tenant.ConnectionGrant (domain) and tenant.ConnectionGrantConfiguration (implementation).
            builder.Services.TryAddSingleton<IConnectionGrantImplementationConfigurationProvider>(sp =>
                new ConnectionGrantImplementationConfigurationProvider(
                    sp.GetRequiredService<ILogger<ConnectionGrantImplementationConfigurationProvider>>(),
                    sp.GetRequiredService<IConfigurationGatewayProvider>(), ConnectionTypes.ConfigurationConnection, "tenant", "ConnectionGrantConfiguration"));
            builder.Services.TryAddSingleton<ConnectionGrantConfigurationProvider>(sp =>
            {
                var domain = new ConnectionGrantConfigurationProvider(
                    sp.GetRequiredService<ILogger<ConnectionGrantConfigurationProvider>>(),
                    sp.GetRequiredService<IConfigurationGatewayProvider>(), ConnectionTypes.ConfigurationConnection, "tenant", "ConnectionGrant");
                domain.Register("ConnectionGrant", sp.GetRequiredService<IConnectionGrantImplementationConfigurationProvider>());
                return domain;
            });
            builder.Services.TryAddSingleton<IConnectionGrantConfigurationProvider>(sp => sp.GetRequiredService<ConnectionGrantConfigurationProvider>());

            // ConnectionAssignment (FDW-1581): tenant.ConnectionAssignment (domain) and tenant.ConnectionAssignmentConfiguration (implementation).
            builder.Services.TryAddSingleton<IConnectionAssignmentImplementationConfigurationProvider>(sp =>
                new ConnectionAssignmentImplementationConfigurationProvider(
                    sp.GetRequiredService<ILogger<ConnectionAssignmentImplementationConfigurationProvider>>(),
                    sp.GetRequiredService<IConfigurationGatewayProvider>(), ConnectionTypes.ConfigurationConnection, "tenant", "ConnectionAssignmentConfiguration"));
            builder.Services.TryAddSingleton<ConnectionAssignmentConfigurationProvider>(sp =>
            {
                var domain = new ConnectionAssignmentConfigurationProvider(
                    sp.GetRequiredService<ILogger<ConnectionAssignmentConfigurationProvider>>(),
                    sp.GetRequiredService<IConfigurationGatewayProvider>(), ConnectionTypes.ConfigurationConnection, "tenant", "ConnectionAssignment");
                domain.Register("ConnectionAssignment", sp.GetRequiredService<IConnectionAssignmentImplementationConfigurationProvider>());
                return domain;
            });
            builder.Services.TryAddSingleton<IConnectionAssignmentConfigurationProvider>(sp => sp.GetRequiredService<ConnectionAssignmentConfigurationProvider>());

            // The resolver of an organization's store reads only singletons; the services that grant and assign read the tenant and the
            // organization, which are scoped (FDW-1581).
            builder.Services.TryAddSingleton<IDocumentStores>(sp =>
                new DocumentStores(
                    sp.GetRequiredService<IConnectionAssignmentConfigurationProvider>(),
                    sp.GetRequiredService<IConnectionGrantConfigurationProvider>(),
                    sp.GetRequiredService<IDocumentConnectionProvider>(),
                    sp.GetService<ILoggerFactory>(),
                    sp.GetService<ILogger<DocumentStores>>()));
            builder.Services.TryAddScoped<IConnectionGrants>(sp =>
                new ConnectionGrants(
                    sp.GetRequiredService<IConnectionGrantConfigurationProvider>(),
                    sp.GetRequiredService<IConnectionAssignmentConfigurationProvider>(),
                    sp.GetRequiredService<IDocumentConnectionProvider>(),
                    sp.GetRequiredService<Fdw.Services.Multitenancy.Abstractions.ITenantProvider>(),
                    sp.GetService<ILogger<ConnectionGrants>>()));
            builder.Services.TryAddScoped<IConnectionAssignments>(sp =>
                new ConnectionAssignments(
                    sp.GetRequiredService<Fdw.Services.Authorization.Abstractions.IOrganizationScope>(),
                    sp.GetRequiredService<IConnectionAssignmentConfigurationProvider>(),
                    sp.GetRequiredService<IConnectionGrantConfigurationProvider>(),
                    sp.GetService<ILogger<ConnectionAssignments>>()));

            builder.Services.TryAddEnumerable(
                ServiceDescriptor.Singleton<IHealthCheckable, ConnectionsHealthCheckable>());

            builder.Services.TryAddScoped<IConnectionHealthService, ConnectionHealthService>();

            // The health monitor's scan bounds are stated here, where it is registered, and a host that
            // wants others replaces this body. After each check it waits until the soonest enabled
            // connection falls due, never less than the first and never more than the second, which is
            // also the longest a newly enabled health check waits to be noticed (FDW-970).
            builder.Services.AddHostedService(sp => new ConnectionHealthMonitorWorker(
                sp.GetRequiredService<IServiceScopeFactory>(),
                TimeSpan.FromSeconds(15),
                TimeSpan.FromMinutes(5),
                sp.GetService<ILogger<ConnectionHealthMonitorWorker>>()));

            builder.Services.TryAddSingleton<IDataConnectionProvider>(sp =>
                (IDataConnectionProvider)sp.GetRequiredService<IConnectionProvider>());
            builder.Services.TryAddSingleton<IDocumentConnectionProvider>(sp =>
                (IDocumentConnectionProvider)sp.GetRequiredService<IConnectionProvider>());

            builder.Services.TryAddSingleton<IServiceConnectionProvider, ServiceConnectionProvider>();

            var registered = collectOptions(builder, loggerFactory);
            if (registered.IsFailure)
                return registered;

            var declaredOptions = Options;
            var optionNames = string.Join(", ", declaredOptions.Select(option => option.Name));

            ServiceTypeLog.DomainOptionsCollected(log, nameof(ConnectionTypes), declaredOptions.Length, optionNames);

            // No factory registration here any more. Each option registers its own implementation
            // provider with this domain in its Initialization body, once a container exists to
            // resolve both out of -- the same place it already registers its implementation
            // CONFIGURATION provider. A domain no longer reaches into its options to wire them.
            ServiceTypeLog.DomainProviderDeclared(log, nameof(ConnectionTypes), providerService);

            builder.Services.AddSingleton<IConnectionProvider>(sp =>
            {
                var provider = new ConnectionProvider(
                    sp.GetService<ILoggerFactory>()?.CreateLogger<ConnectionProvider>()
                    ?? NullLogger<ConnectionProvider>.Instance);

                var stLogger = sp.GetService<ILoggerFactory>()?.CreateLogger<ConnectionTypes>()
                    ?? NullLogger<ConnectionTypes>.Instance;
                ServiceTypeLog.DomainProviderConstructing(stLogger, nameof(ConnectionTypes), provider.GetType().Name);
                try
                {
                    if (sp.GetService<IConnectionConfigurationProvider>() is { } cfgProvider)
                    {
                        var domainResult = provider.Register(cfgProvider);
                        if (domainResult.IsSuccess)
                            ServiceTypeLog.DomainConfigurationSourceAttached(stLogger, nameof(ConnectionTypes), provider.GetType().Name, cfgProvider.GetType().Name);
                        else
                            ServiceTypeLog.DomainConfigurationSourceRejected(stLogger, nameof(ConnectionTypes), provider.GetType().Name, cfgProvider.GetType().Name, domainResult.CurrentMessage);
                    }
                    else
                    {
                        ServiceTypeLog.DomainHasNoConfigurationSource(
                            stLogger,
                            nameof(ConnectionTypes),
                            provider.GetType().Name,
                            typeof(IImplementationConfigurationProvider<IConnectionImplementationConfiguration>).ToString());
                    }
                }
                catch (Exception ex)
                {
                    ServiceTypeLog.FactoryRegistrationException(stLogger, ex, nameof(ConnectionTypes));
                    throw;
                }
                return provider;
            });

            if (declaredOptions.Length == 0)
                ServiceTypeLog.DomainRegisteredWithNoOptions(log, nameof(ConnectionTypes), providerService);
            else
                ServiceTypeLog.DomainRegistered(log, nameof(ConnectionTypes), declaredOptions.Length, optionNames, providerService);

            return GenericResult<IHostApplicationBuilder>.Success(builder);
        });
    }

    // The generated NotFound sentinel answers the host-identity question the only honest way: a connection whose
    // type is not registered says nothing about how it authenticates, so the answer cannot be given.
    private sealed partial class NotFoundConnectionTypes
    {
        /// <inheritdoc />
        protected override IGenericResult<bool> DecideHostIdentity(IConnectionImplementationConfiguration configuration)
            => GenericResult<bool>.Failure(
                Results.ConnectionsResultCodes.ByName("HostIdentityUndetermined"),
                ResultDetails.Create("name", configuration.Name, "reason", "its connection type is not registered"));

        protected override IGenericResult<ConnectionCredentialSlots> DescribeCredentials(IConnectionImplementationConfiguration configuration)
            => GenericResult<ConnectionCredentialSlots>.Failure(
                Results.ConnectionsResultCodes.ByName("CredentialsUndetermined"),
                ResultDetails.Create("name", configuration.Name, "reason", "its connection type is not registered"));

        protected override IGenericResult BindCredentialReferences(
            IConnectionImplementationConfiguration configuration,
            string secretManagerName,
            IReadOnlyDictionary<string, string> secretKeyByField)
            => GenericResult.Failure(
                Results.ConnectionsResultCodes.ByName("CredentialsUndetermined"),
                ResultDetails.Create("name", configuration.Name, "reason", "its connection type is not registered"));
    }
}
