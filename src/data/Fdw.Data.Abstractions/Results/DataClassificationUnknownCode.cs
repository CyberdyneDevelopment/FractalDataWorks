using System.Diagnostics.CodeAnalysis;
using Fdw.Collections.Attributes;
using Fdw.Results;

namespace Fdw.Data.Abstractions.Results;

/// <summary>
/// A request named a <c>ClassificationId</c> that none of the <c>DataClassifications</c> levels declares.
/// </summary>
/// <remarks>
/// 20003 is the catalog's OutOfRange (RESULTCODE-CATALOG.md): the id names no level in the defined
/// set. HTTP 400. It is a refusal, not "unclassified", because a caller who names a level means one
/// (FDW-938). It was 20001 until FDW-955, which InvalidCanonicalLocationFormat already held in this
/// collection: two options sharing an id made the generated ById throw on first use.
/// </remarks>
[TypeOption(typeof(DataStoresResultCodes), "DataClassificationUnknown", RestrictToCurrentCompilation = true)]
[ExcludeFromCodeCoverage]
public sealed class DataClassificationUnknownCode : DataStoresResultCodeBase
{
    /// <summary>
    /// Initializes a new instance of the <see cref="DataClassificationUnknownCode"/> class.
    /// </summary>
    public DataClassificationUnknownCode()
        : base(20003, "DataClassificationUnknown", ResultSeverities.ByName("Error"),
            "Data classification '{ClassificationId}' is not one of the classification levels",
            isRetryable: false)
    {
    }
}
