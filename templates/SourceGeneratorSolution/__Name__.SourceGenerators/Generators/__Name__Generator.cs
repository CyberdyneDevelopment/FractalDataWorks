using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Fdw.SourceGenerators;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace __RootNamespace__.__Name__.SourceGenerators.Generators;

[Generator]
public class __Name__Generator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Register attribute for discovery
        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddSource("__Name__GeneratorAttribute.g.cs", @"// <auto-generated/>
#nullable enable

namespace __RootNamespace__.__Name__.Attributes
{
    [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
    [System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]
    internal sealed class __Name__GeneratorAttribute : System.Attribute
    {
        public __Name__GeneratorAttribute() { }
    }
}
");
        });

        // Find all classes with [__Name__Generator] attribute
        var classesWithAttribute = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                fullyQualifiedMetadataName: "__RootNamespace__.__Name__.Attributes.__Name__GeneratorAttribute",
                predicate: (node, _) => node is ClassDeclarationSyntax,
                transform: (context, _) => GetClassInfo(context))
            .Where(info => info != null)
            .Collect();

        // Generate code for each discovered class
        context.RegisterSourceOutput(classesWithAttribute, (spc, classes) =>
        {
            foreach (var classInfo in classes)
            {
                if (classInfo == null) continue;

                var source = GenerateCode(classInfo);
                spc.AddSource($"{classInfo.ClassName}.g.cs", source);
            }
        });
    }

    private static ClassInfo? GetClassInfo(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol classSymbol)
            return null;

        return new ClassInfo
        {
            ClassName = classSymbol.Name,
            Namespace = classSymbol.ContainingNamespace.ToDisplayString(),
            FullTypeName = classSymbol.ToDisplayString()
        };
    }

    private static string GenerateCode(ClassInfo classInfo)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine($"// Generated {classInfo.ClassName}.g.cs");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {classInfo.Namespace}");
        sb.AppendLine("{");
        sb.AppendLine($"    partial class {classInfo.ClassName}");
        sb.AppendLine("    {");
        sb.AppendLine($"        // Generated code for {classInfo.FullTypeName}");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private sealed class ClassInfo
    {
        public string ClassName { get; set; } = "";
        public string Namespace { get; set; } = "";
        public string FullTypeName { get; set; } = "";
    }
}
