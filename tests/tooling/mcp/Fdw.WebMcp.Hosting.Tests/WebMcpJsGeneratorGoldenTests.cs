using Microsoft.Extensions.Logging.Abstractions;
using Shouldly;
using Xunit;

namespace Fdw.WebMcp.Hosting.Tests;

/// <summary>
/// The whole served script, byte for byte, for a catalogue that exercises every rule.
/// </summary>
/// <remarks>
/// The other generator tests assert one property each. This one exists so that a change to HOW the
/// script is produced cannot change WHAT it says without the diff showing up here. It was captured
/// from the generator before the per-tool plan was extracted, which is what licenses calling that
/// extraction a refactor rather than a behaviour change.
///
/// When the output is meant to change, regenerate it and read the diff line by line: every line
/// that moves is a change to what every agent on every FDW host is told.
/// </remarks>
public class WebMcpJsGeneratorGoldenTests
{
    [Fact]
    [Trait("Priority", "P1")]
    [Trait("Category", "Api")]
    public void TheServedScriptIsExactlyTheGoldenCopy()
    {
        new WebMcpJsGenerator(
                new WebMcpGoldenCatalogue.Registry(WebMcpGoldenCatalogue.Tools()),
                NullLogger<WebMcpJsGenerator>.Instance)
            .Generate(new WebMcpHostSettings("X-Webmcp-Key", "golden-key", SelfBaseAddress: null))
            .ReplaceLineEndings("\n")
            // A raw string literal drops the line break before its closing quotes; the script
            // ends with one, so it is restored here rather than trimmed off both sides -- trimming
            // would let a change to the script's final byte pass unnoticed.
            .ShouldBe(Golden.ReplaceLineEndings("\n") + "\n");
    }

    private const string Golden = """
// Generated by Fdw WebMCP
// Registers AI agent tools via document.modelContext (WebMCP W3C standard).
// The spec moved the API from navigator to document because tools belong to a
// page, and Chrome 150 deprecated the navigator form while the Chrome 149
// origin trial still serves it. Prefer document, accept navigator, so one
// generated script works across the Chrome 149-156 trial window.
(function() {
  var modelContext =
    (typeof document !== 'undefined' && document.modelContext) ||
    (typeof navigator !== 'undefined' && navigator.modelContext) ||
    null;
  if (!modelContext) return;

  // Path parameters travel in the URL, so they are removed from the body a tool sends.
  function strip(input, names) {
    const out = {};
    for (const k of Object.keys(input || {})) if (!names.includes(k)) out[k] = input[k];
    return out;
  }

  // Only values the agent actually supplied are sent: an omitted filter must widen
  // the result, not narrow it to the empty string.
  function query(input, names) {
    const parts = [];
    for (const n of names) {
      const v = (input || {})[n];
      if (v === undefined || v === null || v === "") continue;
      parts.push(encodeURIComponent(n) + "=" + encodeURIComponent(v));
    }
    return parts.join("&");
  }

  modelContext.registerTool({
    name: "list_items",
    description: "List items, optionally filtered.",
    annotations: { readOnlyHint: true },
    inputSchema: {
      type: "object",
      properties: {
        "ReferenceId": { "type": "string" },
        "Take": { "type": "integer" },
        "Since": { "type": "string", "format": "date-time" }
      },
      required: []
    },
    execute: async function(input) {
      let url = "/items";
      const q = query(input, ["ReferenceId", "Take", "Since"]);
      if (q) url += "?" + q;
      const init = {
        method: "GET",
        headers: { "Accept": "application/json", "X-Webmcp-Key": "golden-key" }
      };
      const r = await fetch(url, init);
      if (!r.ok) return { error: r.status + " " + r.statusText };
      return await r.json();
    }
  });

  modelContext.registerTool({
    name: "get_item",
    description: "One item by name.",
    annotations: { readOnlyHint: true },
    inputSchema: {
      type: "object",
      properties: {
        "Name": { "type": "string" }
      },
      required: ["Name"]
    },
    execute: async function(input) {
      let url = "/items/" + encodeURIComponent(input["Name"]);
      const init = {
        method: "GET",
        headers: { "Accept": "application/json", "X-Webmcp-Key": "golden-key" }
      };
      const r = await fetch(url, init);
      if (!r.ok) {
        const failure = { error: r.status + " " + r.statusText };
        try {
          const alt = await fetch("/items", { method: "GET", headers: { "Accept": "application/json", "X-Webmcp-Key": "golden-key" } });
          if (alt.ok) {
            failure.validValues = await alt.json();
            failure.hint = "'Name' did not match. failure.validValues lists what is available; 'list_items' returns the same set.";
          }
        } catch (e) { /* recovery is best-effort; the original failure still returns */ }
        return failure;
      }
      return await r.json();
    }
  });

  modelContext.registerTool({
    name: "create_item",
    description: "Create an item of this tool's service type.",
    inputSchema: {
      type: "object",
      properties: {
        "Name": { "type": "string" },
        "Enabled": { "type": "boolean" },
        "OwnerId": { "type": "string", "format": "uuid" }
      },
      required: []
    },
    execute: async function(input) {
      let url = "/items";
      const init = {
        method: "POST",
        headers: { "Accept": "application/json", "Content-Type": "application/json", "X-Webmcp-Key": "golden-key" },
        body: JSON.stringify(Object.assign(strip(input, []), { "ServiceType": "MsSql" }))
      };
      const r = await fetch(url, init);
      if (!r.ok) return { error: r.status + " " + r.statusText };
      return await r.json();
    }
  });

  modelContext.registerTool({
    name: "delete_item",
    description: "Delete one item by name.",
    inputSchema: {
      type: "object",
      properties: {
        "Name": { "type": "string" }
      },
      required: ["Name"]
    },
    execute: async function(input) {
      let url = "/items/" + encodeURIComponent(input["Name"]);
      const init = {
        method: "DELETE",
        headers: { "Accept": "application/json", "X-Webmcp-Key": "golden-key" }
      };
      const r = await fetch(url, init);
      if (!r.ok) {
        const failure = { error: r.status + " " + r.statusText };
        try {
          const alt = await fetch("/items", { method: "GET", headers: { "Accept": "application/json", "X-Webmcp-Key": "golden-key" } });
          if (alt.ok) {
            failure.validValues = await alt.json();
            failure.hint = "'Name' did not match. failure.validValues lists what is available; 'list_items' returns the same set.";
          }
        } catch (e) { /* recovery is best-effort; the original failure still returns */ }
        return failure;
      }
      return await r.json();
    }
  });

  modelContext.registerTool({
    name: "ping",
    description: "Liveness.",
    annotations: { readOnlyHint: true },
    inputSchema: {
      type: "object",
      properties: {},
      required: []
    },
    execute: async function(input) {
      let url = "/ping";
      const init = {
        method: "GET",
        headers: { "Accept": "application/json", "X-Webmcp-Key": "golden-key" }
      };
      const r = await fetch(url, init);
      if (!r.ok) return { error: r.status + " " + r.statusText };
      return await r.json();
    }
  });

})();
""";
}
