using System.Linq;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Xunit;

namespace Fdw.Collections.SourceGenerators.Tests;

/// <summary>
/// End-to-end tests for generated TypeCollection code (modeled after Microsoft pattern).
/// Tests that generated code actually compiles and behaves correctly.
/// </summary>
public class TypeCollectionGeneratedCodeTests
{
    [Fact]
    [Trait("Priority", "P0")]
    [Trait("Category", "SourceGen")]
    public async Task GeneratedCollection_Compiles()
    {
        var source = @"
using Fdw.Collections;
using Fdw.Collections.Attributes;

namespace Test;

public abstract class ConnectionTypeBase : TypeOptionBase<int, ConnectionTypeBase>
{
    protected ConnectionTypeBase(int id, string name) : base(id, name) { }
}

[TypeCollection(typeof(ConnectionTypeBase), typeof(ConnectionTypeBase), typeof(ConnectionTypes))]
public partial class ConnectionTypes : TypeCollectionBase<ConnectionTypeBase, ConnectionTypeBase>
{
}

[TypeOption(typeof(ConnectionTypes), ""MsSql"")]
public class MsSqlConnectionType : ConnectionTypeBase
{
    public MsSqlConnectionType() : base(1, ""MsSql"") { }
}

[TypeOption(typeof(ConnectionTypes), ""PostgreSql"")]
public class PostgreSqlConnectionType : ConnectionTypeBase
{
    public PostgreSqlConnectionType() : base(2, ""PostgreSql"") { }
}
";

        var (compilation, diagnostics) = CompilationHelper.RunGenerator(source);

        // No generator errors
        Assert.Empty(diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));

        // Verify generated code has expected content
        var generated = CompilationHelper.GetGeneratedOutput(compilation, "ConnectionTypes.TypeCollection.g.cs");
        Assert.NotNull(generated);
        Assert.Contains("partial class ConnectionTypes", generated);
        Assert.Contains("MsSql", generated);
        Assert.Contains("PostgreSql", generated);
    }

    [Fact]
    [Trait("Priority", "P0")]
    [Trait("Category", "SourceGen")]
    public async Task GeneratedCollection_ByName_ReturnsCorrectType()
    {
        var source = @"
using Fdw.Collections;
using Fdw.Collections.Attributes;

namespace Test;

public abstract class TestBase : TypeOptionBase<int, TestBase>
{
    protected TestBase(int id, string name) : base(id, name) { }
}

[TypeCollection(typeof(TestBase), typeof(TestBase), typeof(Tests))]
public partial class Tests : TypeCollectionBase<TestBase, TestBase>
{
}

[TypeOption(typeof(Tests), ""Alpha"")]
