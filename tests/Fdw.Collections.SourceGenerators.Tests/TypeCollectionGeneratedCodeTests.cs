    [Fact]
    [Trait("Priority", "P0")]
    [Trait("Category", "SourceGen")]
    public async Task ParentChildCollection_GeneratesCorrectHierarchy()
    {
        var source = @"
using Fdw.Collections;
using Fdw.Collections.Attributes;

namespace Test;

// Parent base
public abstract class ParentBase : TypeCollectionBase<ChildBase, ChildBase>
{
    protected ParentBase(string name) : base(name) { }
}

// Parent collection
[TypeCollection(typeof(ParentBase), typeof(ParentBase), typeof(Parents))]
public partial class Parents : TypeCollectionBase<ParentBase, ParentBase>
{
}

// Child base
public abstract class ChildBase : TypeOptionBase<int, ChildBase>
{
    protected ChildBase(int id, string name) : base(id, name) { }
}

// Child collection (member of parent)
[TypeCollection(typeof(ChildBase),
                typeof(ChildBase),
                typeof(MsSqlTypes),
                TypeOption = typeof(Parents),
                TypeOptionName = ""MsSql"")]
public partial class MsSqlTypes : ParentBase
{
    protected MsSqlTypes() : base(""Microsoft SQL Server"") { }
}

// TypeOption in child collection
[TypeOption(typeof(MsSqlTypes), ""Int32"")]
public class Int32Type : ChildBase
{
    public Int32Type() : base(1, ""Int32"") { }
}
";

        var (compilation, diagnostics) = CompilationHelper.RunGenerator(source);

        Assert.Empty(diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));

        // Parent should reference child
        var parentGenerated = CompilationHelper.GetGeneratedOutput(compilation, "Parents.TypeCollection.g.cs");
        Assert.NotNull(parentGenerated);
        Assert.Contains("MsSql", parentGenerated);

        // Child should have its options
        var childGenerated = CompilationHelper.GetGeneratedOutput(compilation, "MsSqlTypes.TypeCollection.g.cs");
        Assert.NotNull(childGenerated);
        Assert.Contains("Int32", childGenerated);
    }
}
